#Clearly, two columns are highly correlated as per our threshold value.

# Drop (remove) the highly correlated features from the training data
X_train.drop(corr_features, axis=1, inplace=True)

# Drop the same highly correlated features from the test data
# This keeps the training and test datasets consistent
X_test.drop(corr_features, axis=1, inplace=True)

