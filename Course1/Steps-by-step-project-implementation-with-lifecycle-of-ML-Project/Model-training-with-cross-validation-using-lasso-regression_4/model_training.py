# Function to find highly correlated features based on a given threshold
def correlation(dataset, threshold):

    # Create an empty set to store names of correlated columns
    col_corr = set()

    # Calculate the correlation matrix for the dataset
    corr_matrix = dataset.corr()

    # Loop through each column in the correlation matrix
    for i in range(len(corr_matrix.columns)):

        # Compare the current column with all previous columns
        for j in range(i):

            # If the absolute correlation value is greater than the threshold
            if abs(corr_matrix.iloc[i, j]) > threshold:

                # Get the name of the correlated column
                colname = corr_matrix.columns[i]

                # Add the column name to the set
                col_corr.add(colname)

    # Return the set of highly correlated feature names
    return col_corr

# Threshold decided by a domain expert is 0.85
# This means features with correlation greater than 0.85 will be considered highly correlated
corr_features = correlation(X_train, 0.85)

